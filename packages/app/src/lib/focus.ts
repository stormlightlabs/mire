import type { FileDetail, FileSummary } from './review';
import { treeGroups } from './tree';

/** Input types that take no typed text, so single-key shortcuts still apply while one has focus. */
const NON_TEXT_INPUTS = ['checkbox', 'radio', 'button', 'submit', 'reset'];

/** A repository path split for display: the directory, with its trailing slash, and the file name. */
export type SplitPath = { directory: string; name: string };

/** The file a reader moves to with the previous and next keys, and where the shown file sits in the review. */
export type FilePosition = { index: number; total: number; previous: FileSummary | null; next: FileSummary | null };

/**
 * Orders files as the file tree lists them: files not marked generated by
 * path, then the generated ones in review order. Moving to the previous or next
 * file follows this order, so focus mode walks the files in the order the tree
 * shows.
 */
export function fileOrder(files: FileSummary[]): FileSummary[] {
	const { source, generated } = treeGroups(files);
	return [...source, ...generated];
}

/**
 * Finds the shown file in the tree order and its neighbours. The file is
 * matched by raw path, since a source change gives it a new `id`. The ends do
 * not wrap: the first file has no previous one and the last has no next one.
 */
export function filePosition(files: FileSummary[], shown: Pick<FileSummary, 'path'> | null): FilePosition | null {
	if (!shown) return null;
	const ordered = fileOrder(files);
	const index = ordered.findIndex((file) => file.path.raw === shown.path.raw);
	if (index < 0) return null;
	return {
		index,
		total: ordered.length,
		previous: ordered[index - 1] ?? null,
		next: ordered[index + 1] ?? null
	};
}

/** Splits a display path into its directory and file name, so the name can stand out. */
export function splitPath(display: string): SplitPath {
	const slash = display.lastIndexOf('/');
	return slash < 0
		? { directory: '', name: display }
		: { directory: display.slice(0, slash + 1), name: display.slice(slash + 1) };
}

/**
 * Describes a file's change in a few words: its status, then its line count.
 * An added or deleted file reports how many lines it has; any other text file
 * reports the lines added and removed in its captured hunks.
 */
export function changeSummary(file: Pick<FileDetail, 'status' | 'content' | 'generated'>): string {
	const parts = [statusLabel(file.status)];
	if (file.content.kind === 'binary') {
		parts.push('binary');
	} else {
		let additions = 0;
		let deletions = 0;
		for (const hunk of file.content.hunks) {
			for (const line of hunk.lines) {
				if (line.kind === 'addition') additions += 1;
				else if (line.kind === 'deletion') deletions += 1;
			}
		}
		if (file.status === 'added') parts.push(lineCount(additions));
		else if (file.status === 'deleted') parts.push(lineCount(deletions));
		else parts.push(`+${additions} −${deletions}`);
	}
	if (file.generated) parts.push('generated');
	return parts.join(' · ');
}

/**
 * Reports whether a key press goes to a control that takes typed text, where
 * the review's single-key shortcuts must not fire. A checkbox or a button does
 * not take text, so the keys still work after clicking one.
 */
export function takesText(target: EventTarget | null): boolean {
	if (!target || !('tagName' in target)) return false;
	const element = target as { tagName: string; type?: string; isContentEditable?: boolean };
	if (element.isContentEditable) return true;
	const tag = element.tagName.toLowerCase();
	if (tag === 'textarea' || tag === 'select') return true;
	return tag === 'input' && !NON_TEXT_INPUTS.includes(element.type ?? 'text');
}

function statusLabel(status: string): string {
	switch (status) {
		case 'added':
			return '+ New file';
		case 'deleted':
			return '− Deleted file';
		default:
			return status.charAt(0).toUpperCase() + status.slice(1);
	}
}

function lineCount(count: number): string {
	return `${count} line${count === 1 ? '' : 's'}`;
}
